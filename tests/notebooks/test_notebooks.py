"""Smoke-execute every notebook's jupytext .py:percent mirror.

Each notebook is run as a subprocess (clean interpreter per notebook) with
NEUROVLM_SMOKE=1, which caps training loops to one epoch over a couple of
batches (see smoke_bootstrap.py) so real data/model code paths get exercised
in seconds instead of hours. This does not validate numerical quality; it
only proves the notebook's code still runs after refactors.

Separate from the fast deterministic suite: run explicitly with

    pytest tests/notebooks -m notebook_smoke -v

Not part of the default `pytest` collection filter used in CI.
"""

