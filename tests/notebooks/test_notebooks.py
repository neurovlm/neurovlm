def _discover_notebooks() -> list[Path]:
    return sorted(DOCS_ROOT.rglob("*.ipynb"))


def _relative_py(nb_path: Path) -> Path:
    return nb_path.relative_to(DOCS_ROOT).with_suffix(".py")


NOTEBOOKS = _discover_notebooks()


def _marks_for(rel_key: str) -> list:
    marks = [pytest.mark.notebook_smoke, pytest.mark.slow, pytest.mark.network]
    if rel_key in KNOWN_UNRUNNABLE:
        marks.append(pytest.mark.skip(reason=KNOWN_UNRUNNABLE[rel_key]))
    return marks


def _params():
    for nb in NOTEBOOKS:
        rel_key = str(_relative_py(nb))
        yield pytest.param(nb, id=rel_key, marks=_marks_for(rel_key))


@pytest.mark.parametrize("notebook_path", list(_params()))
def test_notebook_smoke(notebook_path: Path):
    py_path = notebook_path.with_suffix(".py")
    assert py_path.is_file(), f"missing jupytext mirror for {notebook_path}; run `jupytext --sync {notebook_path}`"

    rel_key = str(_relative_py(notebook_path))
    timeout = TIMEOUT_OVERRIDES.get(rel_key, DEFAULT_TIMEOUT)

    env = dict(os.environ)
    env["NEUROVLM_SMOKE"] = "1"
    env["MPLBACKEND"] = "Agg"
    env["TOKENIZERS_PARALLELISM"] = "false"
    env["PYTHONPATH"] = str(REPO_ROOT) + os.pathsep + env.get("PYTHONPATH", "")

    result = subprocess.run(
        [sys.executable, str(RUNNER), str(py_path)],
        cwd=py_path.parent,
        env=env,
        capture_output=True,
        text=True,
        timeout=timeout,
    )

    if result.returncode != 0:
        tail_out = "\n".join(result.stdout.splitlines()[-60:])
        tail_err = "\n".join(result.stderr.splitlines()[-60:])
        pytest.fail(
            f"{rel_key} exited {result.returncode}\n--- stdout (tail) ---\n{tail_out}\n"
            f"--- stderr (tail) ---\n{tail_err}"
        )
